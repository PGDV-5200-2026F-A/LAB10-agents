#!/usr/bin/env python3
"""
ANSUR data pipeline - asset packing.

Wraps the Stage 1 and Stage 2 JSON outputs as JavaScript globals so the
dashboard works when opened directly from disk (file://), where fetch() of a
local JSON file is blocked by the browser's same-origin policy.

Writes:
  dist/ansur-data.js   - window.ANSUR_DATA  (records + metadata)
  dist/ansur-stats.js  - window.ANSUR_STATS (descriptives, covariance, histograms)

Both files are plain <script> payloads: load them with a <script> tag, and the
globals are ready before chart.js runs.

Determinism: identical bytes on every run (no timestamps, stable key order).

Usage:  python3 -I tools/pack_data.py
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIST = os.path.join(ROOT, "dist")

SOURCES = [
    ("data/ansur.json", "dist/ansur-data.js", "ANSUR_DATA", "ANSUR dataset"),
    ("data/ansur-stats.json", "dist/ansur-stats.js", "ANSUR_STATS", "ANSUR statistics"),
]


def pack(source_rel, target_rel, global_name, title):
    source_path = os.path.join(ROOT, source_rel)
    if not os.path.exists(source_path):
        sys.exit(f"missing input: {source_path}")
    with open(source_path, encoding="utf-8") as handle:
        payload = json.load(handle)
    target_path = os.path.join(ROOT, target_rel)
    os.makedirs(os.path.dirname(target_path), exist_ok=True)
    with open(target_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"/* {title} - generated by tools/pack_data.py. Do not edit. */\n")
        handle.write(f"window.{global_name} = ")
        json.dump(payload, handle, separators=(",", ":"), sort_keys=False)
        handle.write(";\n")
    size = os.path.getsize(target_path)
    print(f"wrote {target_rel} ({size:,} bytes) -> window.{global_name}")


def main():
    for source_rel, target_rel, global_name, title in SOURCES:
        pack(source_rel, target_rel, global_name, title)


if __name__ == "__main__":
    main()
